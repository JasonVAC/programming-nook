def translate_sh(line):
    match = re.match(r'\.SH\s+"([^"]*)"(.*)', line)
    if match:
        title = match.group(1)
        rest = match.group(2)
        translated = SH_TRANS.get(title.upper(), title)
        if translated != title:
            return f'.SH "{translated}"{rest}'
    match2 = re.match(r'\.SH\s+(\S+)(.*)', line)
    if match2:
        title = match2.group(1)
        rest = match2.group(2)
        if title in SH_TRANS:
            return f'.SH {SH_TRANS[title]}{rest}'
    return line

def translate_ss(line):
    match = re.match(r'\.SS\s+"([^"]*)"(.*)', line)
    if match:
        title = match.group(1)
        rest = match.group(2)
        translated = SH_TRANS.get(title.upper(), title)
        if translated != title:
            return f'.SS "{translated}"{rest}'
    match2 = re.match(r'\.SS\s+(\S+)(.*)', line)
    if match2:
        title = match2.group(1)
        rest = match2.group(2)
        if title.upper() in SH_TRANS:
            return f'.SS {SH_TRANS[title.upper()]}{rest}'
    return line


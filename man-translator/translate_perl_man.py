count = 0
for fname in FILES:
    src = f"/usr/share/man/man1/{fname}.gz"
    dest = f"/tmp/man1_zh/{fname}"
    
    result = subprocess.run(["zcat", src], capture_output=True, text=True)
    if result.returncode != 0:
        print(f"ERROR reading {src}: {result.stderr}", file=sys.stderr)
        continue
    
    lines = result.stdout.split('\n')
    out_lines = []
    
    for line in lines:
        stripped = line.strip()
        if stripped.startswith('.SH '):
            line = translate_sh(line)
        elif stripped.startswith('.SS '):
            line = translate_ss(line)
        elif stripped.startswith('.IX Header '):
            # Translate IX Header entries
            header_match = re.match(r'(\.IX Header\s+)"([^"]*)"(.*)', line)
            if header_match:
                prefix = header_match.group(1)
                title = header_match.group(2)
                rest = header_match.group(3)
                translated = SH_TRANS.get(title.upper(), title)
                if translated != title:
                    line = f'{prefix}"{translated}"{rest}'
        out_lines.append(line)
    
    with open(dest, 'w', encoding='utf-8') as f:
        f.write('\n'.join(out_lines))
    
    subprocess.run(["gzip", "-c", dest], capture_output=True)
    subprocess.run(["sudo", "bash", "-c", f"gzip -c {dest} | tee /usr/share/man/zh_CN/man1/{fname}.gz > /dev/null"], capture_output=True)
    
    count += 1
    if count % 5 == 0:
        print(f"  ... {count}/{len(FILES)}", file=sys.stderr)

